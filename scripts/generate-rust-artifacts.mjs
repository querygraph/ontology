// Generates the Rust crate's inputs from the canonical JS engine, so the two
// stacks cannot drift silently:
//   dist/seed.json                          — the seed, single source of truth
//   rust/src/tables.rs                      — Unicode range tables, transcribed
//   rust/tests/fixtures/normalization-golden.json — cross-language key parity
import { mkdirSync, writeFileSync } from 'node:fs'
import {
  SEED_CONCEPTS,
  TOPIC_ALPHANUMERIC_CODEPOINT_RANGES,
  TOPIC_FORMAT_CODEPOINT_RANGES,
  TOPIC_MARK_CODEPOINT_RANGES,
  buildSeedSnapshot,
  extractSeedTopics,
  normalizeTopicLabel,
} from '../dist/index.js'

mkdirSync('rust/ontology-core/src', { recursive: true })
mkdirSync('rust/ontology-core/tests/fixtures', { recursive: true })

// ---- seed ----
writeFileSync('dist/seed.json', JSON.stringify({ version: 1, concepts: SEED_CONCEPTS }, null, 1))

// ---- dash ranges (JS \p{Pd} plus U+2212), computed from the runtime ----
const dashRanges = []
let start = null
for (let cp = 0; cp <= 0x11000; cp += 1) {
  const isDash = /[\p{Pd}−]/u.test(String.fromCodePoint(cp))
  if (isDash && start === null) start = cp
  if (!isDash && start !== null) {
    dashRanges.push([start, cp - 1])
    start = null
  }
}

const rustTable = (name, ranges) =>
  `pub const ${name}: &[(u32, u32)] = &[\n${ranges.map(([a, b]) => `    (0x${a.toString(16)}, 0x${b.toString(16)}),`).join('\n')}\n];\n`

writeFileSync('rust/ontology-core/src/tables.rs', [
  '// GENERATED by scripts/generate-rust-artifacts.mjs from the canonical JS',
  '// normalization tables (Unicode 17.0). Do not edit by hand; regenerate.',
  '',
  rustTable('FORMAT_RANGES', TOPIC_FORMAT_CODEPOINT_RANGES),
  rustTable('MARK_RANGES', TOPIC_MARK_CODEPOINT_RANGES),
  rustTable('ALPHANUMERIC_RANGES', TOPIC_ALPHANUMERIC_CODEPOINT_RANGES),
  rustTable('DASH_RANGES', dashRanges),
].join('\n'))

// ---- golden normalization fixture ----
const labels = [
  ...SEED_CONCEPTS.map((concept) => concept.name),
  ...SEED_CONCEPTS.flatMap((concept) => concept.aliases ?? []),
  'C', 'C++', 'C#', 'F#', '.NET', 'Node.js', 'CI/CD', 'CI / CD', 'c＋＋',
  '  Machine   Learning ', 'Don’t Panic', "rock 'n' roll", 'AT&T',
  'naïve café', 'Neo—Tokyo', 'a–b—c', 'B♯ minor', 'MÜNCHEN',
  '​zero​width﻿', 'Ελληνικά', 'русский панк', '日本語テスト',
  'straße', 'İstanbul', ' São Paulo', 'a/b/c//d', '..dots..', '//lead/trail/.',
  'ｆｕｌｌｗｉｄｔｈ', '①②③', 'ﬁne ﬂow', 'x́ composed', 'عَرَبِي',
]
const golden = labels.map((label) => ({ label, key: normalizeTopicLabel(label) }))

// ---- extraction fixture ----
const text = 'Python and machine learning ruined my feed: it is all AI slop and LLM demos now. Even the group chats agree.'
const extraction = {
  text,
  slugs: extractSeedTopics(text, buildSeedSnapshot()).map((entry) => entry.concept.slug).sort(),
}

writeFileSync('rust/ontology-core/tests/fixtures/normalization-golden.json', JSON.stringify({ golden, extraction }, null, 1))
console.log(`seed.json (${SEED_CONCEPTS.length} concepts), tables.rs, golden fixture (${golden.length} labels) written`)
